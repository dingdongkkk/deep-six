export const CHAR_W = 6;
export const CHAR_H = 8;

const cache = new Map();

function glyph(ch, colorKey) {
  const key = colorKey + ch;
  let cv = cache.get(key);
  if (cv) return cv;
  const rows = (G[ch] || G['?']).split('/');
  cv = document.createElement('canvas');
  cv.width = CHAR_W;
  cv.height = CHAR_H;
  const g = cv.getContext('2d');
  g.fillStyle = PAL[colorKey] || colorKey;
  for (let y = 0; y < rows.length; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      if (rows[y][x] === '#') g.fillRect(x, y, 1, 1);
    }
  }
  cache.set(key, cv);
  return cv;
}

export function drawText(g, text, x, y, colorKey = 'g', scale = 1) {
  const s = String(text).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch !== ' ') {
      const cv = glyph(ch, colorKey);
      g.drawImage(cv, x + i * CHAR_W * scale, y, CHAR_W * scale, CHAR_H * scale);
    }
  }
  return s.length * CHAR_W * scale;
}

export function textWidth(text, scale = 1) {
  return String(text).length * CHAR_W * scale;
}

export function drawTextCentered(g, text, cx, y, colorKey = 'g', scale = 1) {
  const w = textWidth(text, scale);
  return drawText(g, text, Math.round(cx - w / 2), y, colorKey, scale);
}
